"""PLAN_V6_REVISION.md V6-4, pipeline step 3.

Picks per_market_best fairly: scores every one of the study's trained/naive
models (never a blend) by MAE over each market's VALIDATION window -- the
60 days right before that market's test window, config/study.yaml's
validation_window -- using the same analysis.forecast_error_metrics the
dashboard uses. The test window itself is never scored here, so the blend
choice can't leak test-window information into the comparison it then
takes part in. aFRR+ and aFRR- are picked separately, like every other
market.

Writes config/forecast_blends.yaml: per_market_best: {day_ahead, fcr,
afrr_pos, afrr_neg}, with a generated-by header recording the window, the
metric, and the MAE table that produced the choice.

    python pipeline/03_select_blend.py [--dry-run]
"""
from __future__ import annotations

import argparse
import datetime as dt
import sys
from pathlib import Path

import pandas as pd

_REPO_ROOT = Path(__file__).resolve().parents[1]
for _p in (_REPO_ROOT, _REPO_ROOT / "app"):
    if str(_p) not in sys.path:
        sys.path.insert(0, str(_p))

from analysis import forecast_error_metrics  # noqa: E402
from data_loader import load_median_forecasts  # noqa: E402

from src.config import CONFIG_DIR, StudyConfig, load_study_config  # noqa: E402

MARKETS = ["day_ahead", "fcr", "afrr_pos", "afrr_neg"]
_EMPTY_FORECASTS = pd.DataFrame(columns=["market", "model", "target_time", "y_pred", "y_true"])


def select_blend(study: StudyConfig, forecasts: pd.DataFrame) -> tuple[dict[str, str], dict[str, dict[str, float]]]:
    """Returns (per_market_best, mae_by_market); mae_by_market is
    {market: {model: mae}}, kept so callers can print or record it
    alongside the choice it produced."""
    if study.validation_window is None:
        raise SystemExit(
            "config/study.yaml has no validation_window -- add one (PLAN_V6_REVISION.md V6-4) "
            "before selecting a blend."
        )
    local_day = forecasts["target_time"].dt.date if not forecasts.empty else None

    per_market_best: dict[str, str] = {}
    mae_by_market: dict[str, dict[str, float]] = {}
    for market in MARKETS:
        window = study.validation_window[market]
        if forecasts.empty:
            in_window = forecasts
        else:
            in_window = forecasts[
                (forecasts["market"] == market)
                & (local_day >= window.start) & (local_day <= window.end)
                & forecasts["model"].isin(study.models)
            ]
        errors = forecast_error_metrics(in_window if not in_window.empty else _EMPTY_FORECASTS)
        if errors.empty:
            raise SystemExit(
                f"No validation-window ({window.start}..{window.end}) forecasts for market "
                f"'{market}' yet -- run pipeline/02_backtest_forecasts.py first."
            )
        mae = errors.xs(market, level="market")["mae"]
        per_market_best[market] = mae.idxmin()
        mae_by_market[market] = mae.to_dict()
    return per_market_best, mae_by_market


def render_forecast_blends_yaml(study: StudyConfig, per_market_best: dict[str, str], mae_by_market: dict) -> str:
    lines = [
        "# Named per-market forecast model blends (PLAN_V4_REVISION.md section 3).",
        "# A blend name resolves through src.data.forecast_loader.load_raw_y_pred to",
        "# one real model per market -- forecast_model stays a flat scalar everywhere",
        "# else (batch resume, skip-log scanning, export, dashboard filters).",
        "#",
        f"# GENERATED by pipeline/03_select_blend.py for study '{study.name}' on "
        f"{dt.date.today().isoformat()}. Do not hand-edit per_market_best below;",
        "# re-run the script instead (PLAN_V6_REVISION.md V6-4).",
        "#",
        "# Picked by lowest MAE on each market's VALIDATION window (never the test",
        "# window), via analysis.forecast_error_metrics:",
    ]
    for market in MARKETS:
        window = study.validation_window[market]
        lines.append(f"#   {market} ({window.start}..{window.end}):")
        for model, mae in sorted(mae_by_market[market].items(), key=lambda kv: kv[1]):
            marker = " <- picked" if model == per_market_best[market] else ""
            lines.append(f"#     {model}: MAE {mae:.3f}{marker}")
    lines.append("per_market_best:")
    lines += [f"  {market}: {per_market_best[market]}" for market in MARKETS]
    return "\n".join(lines) + "\n"


def main(argv=None) -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dry-run", action="store_true", help="Print the chosen blend without writing the file")
    parser.add_argument("--out-path", type=Path, default=CONFIG_DIR / "forecast_blends.yaml")
    args = parser.parse_args(argv)

    study = load_study_config()
    forecasts = load_median_forecasts()
    per_market_best, mae_by_market = select_blend(study, forecasts)

    print(f"[03_select_blend] study: {study.name}")
    for market in MARKETS:
        window = study.validation_window[market]
        print(f"  {market} ({window.start}..{window.end}): best = {per_market_best[market]}")
        for model, mae in sorted(mae_by_market[market].items(), key=lambda kv: kv[1]):
            print(f"      {model}: MAE {mae:.3f}")

    if args.dry_run:
        print(f"--dry-run: not writing {args.out_path}.")
        return

    args.out_path.write_text(render_forecast_blends_yaml(study, per_market_best, mae_by_market), encoding="utf-8")
    print(f"  wrote {args.out_path}")


if __name__ == "__main__":
    main()
